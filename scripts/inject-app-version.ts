import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { z } from 'zod';

const ThinPjsonSchema = z.object({
  version: z
    .string()
    .regex(
      /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-((?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*)(?:\.(?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*))*))?(?:\+([0-9a-zA-Z-]+(?:\.[0-9a-zA-Z-]+)*))?$/,
    ),
});

function injectAppVersion() {
  const getConstantsPath = path.join(
    import.meta.dirname,
    '../src',
    'shared',
    'constants.gen.ts',
  );
  const pjsonPath = path.join(import.meta.dirname, '../package.json');
  const { version } = ThinPjsonSchema.parse(
    JSON.parse(fs.readFileSync(pjsonPath, 'utf-8')),
  );

  const contents: string[] = [
    `/* this file is generated by inject-app-version.ts. DO NOT HAND EDIT */`,
    `export const TASTY_LIMA_VERSION = "${version}" as const;`,
    '',
  ];
  fs.writeFileSync(getConstantsPath, contents.join(os.EOL), 'utf-8');
}

injectAppVersion();

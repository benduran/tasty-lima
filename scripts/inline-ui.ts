import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { glob } from 'glob';
import type { FakeFsEntry } from '../src/cli/fake-fs/fake-fs.ts';
import { FakeFsEntrySchema } from '../src/cli/fake-fs/fake-fs.ts';

const UI_DIST_DIR = path.join(import.meta.dirname, '../dist');
const distFiles = await glob(path.join(UI_DIST_DIR, '**/**'), {
  absolute: true,
  nodir: true,
});
const fakeFsGenerated = path.join(
  import.meta.dirname,
  '../src',
  'cli',
  'fake-fs',
  'content.gen.ts',
);
await fs.mkdir(path.dirname(fakeFsGenerated), { recursive: true });
try {
  await fs.rm(fakeFsGenerated, { force: true });
} catch {
  /* no-op */
}

const fakes: FakeFsEntry[] = [];

for (const fp of distFiles) {
  const relPath = path.relative(UI_DIST_DIR, fp);
  fakes.push(
    FakeFsEntrySchema.parse({
      b64Contents: (await fs.readFile(fp)).toString('base64'),
      filename: path.basename(relPath),
      relPath,
    } satisfies FakeFsEntry),
  );
}

const toWrite: string[] = [
  '/* THIS FILE IS GENERATED BY inline-ui.ts - DO NOT HAND EDIT */',
  "import { FakeFsEntrySchema } from './fake-fs.ts';",
  "import type { FakeFsEntry } from './fake-fs.ts';",
  `export const FAKE_FS: FakeFsEntry[] = FakeFsEntrySchema.array().parse(${JSON.stringify(fakes)});`,
  '',
];

await fs.writeFile(fakeFsGenerated, toWrite.join(os.EOL), 'utf-8');
